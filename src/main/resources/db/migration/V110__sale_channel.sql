-- 접수경로(온라인/수기) — 프론트 I-2(2026-11-02).
--
-- 근거: 10/27 명세 §2-1 "**수기 주문과 온라인(특약점) 주문을 함께 보여주고**, 특약점 사이트와
-- 서로 연동한다." 함께 보여주려면 **둘을 가를 칸**이 있어야 한다 — 지금 응답으로는
-- 구분할 수 없어 프론트가 메모 앞에 「[수기]」를 붙여 쓰고 있었다.
--
-- 값은 둘이다 — ONLINE(특약점 사이트에서 들어옴) / MANUAL(매출등록에서 수기).
-- ‼️**비어 있으면 수기로 본다.** 이관분·기존 등록분이 전부 비어 있는데, 특약점 사이트 연동은
--   2026-11 에 열렸으므로 그 전 주문은 전부 수기가 맞다. 기본값을 박아 넣지 않고 NULL 로
--   두는 이유는, 나중에 "값이 없다"와 "수기로 지정했다"를 구분해야 할 수 있어서다.
ALTER TABLE sales
    ADD COLUMN channel VARCHAR(10) NULL COMMENT '접수경로 ONLINE/MANUAL. 비면 수기(MANUAL)';

CREATE INDEX ix_sales_channel ON sales (channel);
