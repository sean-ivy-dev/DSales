-- 입력 가능 최소 거래일(= 그 전 날짜로는 등록·날짜변경 불가). 근거: 「매출 마무리」 §2-3 ㄱ —
-- "11/30 이전 날짜 입력을 서버에서 막기(매출·수금·주문, 12/1~10). 「입력하면 알려 달라」보다
--  막는 쪽으로. 관리자만 풀 수 있게."
--
-- ★왜 필요한가 — 12/10~11 이관은 **기존 프로그램의 11월 마감 뒤 값**을 그대로 싣는다.
--   그 사이(12/1~12/10)에 담당자가 11월 이전 날짜로 새로 입력하면, 이관이 같은 기간을
--   다시 실으면서 **같은 거래가 두 번** 남거나 이관값이 그 입력을 덮는다. 월마감
--   (period_locks)으로는 못 막는다 — 마감은 달 단위라 11월을 잠그면 10월은 열려 있고,
--   11월을 잠그는 시점 자체가 이관 뒤다.
--
-- ★왜 월마감과 따로 두는가 — 월마감은 "그 달의 재무를 확정했다"는 뜻이고 이 값은
--   "이 날짜 **이전**은 이관이 담당한다"는 뜻이다. 적용 범위도 다르다(마감은 그 달만,
--   이 값은 그 날 이전 전부).
--
-- ★왜 환경변수가 아니라 DB인가 — V117(재고현황 전환일)과 같은 선택이다. 이관 날짜가
--   밀리면 관리자가 즉시 바꿔야 하고, 그걸 위해 재배포하는 건 느리다.
--
-- 싱글톤 행(id=1). 비어 있으면 제한 없음(현행 그대로) — 올려도 아무것도 바뀌지 않는다.
CREATE TABLE entry_date_floor_setting (
    id BIGINT NOT NULL,
    floor_date DATE NULL COMMENT '이 날짜 이전 거래일로는 등록·날짜변경 불가. 비어 있으면 제한 없음',
    created_at DATETIME NOT NULL,
    created_by VARCHAR(100) NULL,
    updated_at DATETIME NULL,
    updated_by VARCHAR(100) NULL,
    PRIMARY KEY (id)
);

