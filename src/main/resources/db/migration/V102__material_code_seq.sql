-- 자재코드 자동 채번(10/27 검수 피드백 §11-3).
--   원문: "자재 등록에서 자재코드를 직접 입력하지 않고 자동으로 끌어와 채운다(확정).
--          어디서 끌어올지는 개발이 정한다. 기존 매출프로그램과 DSRE의 자재코드 체계를
--          확인해 같은 규칙으로 맞춘다."
--
-- ★DSRE 운영덤프(2026-10-26) 실측으로 정한 규칙 = **10만 번대 순수 숫자**.
--   · DSRE `tbl_materials_info.MAT_CD` 는 int auto_increment (실값 1 ~ 12,334, 10,991건).
--     자재의 정체성은 코드가 아니라 DTL_CD(시행) × MAT_GN(구분) × 과목에 있고,
--     과목은 컬럼이 없어 MAT_NM("2026 더 프리미엄 고2 11월 국어")에 글자로만 들어 있다.
--   · 즉 DSRE 의 "규칙"은 그냥 순번이다. 지시대로 **같은 규칙(순수 숫자)** 을 따른다.
--   · 다만 1번부터 쓰면 DSRE 자재와 같은 번호가 서로 다른 자재를 가리킨다
--     (발주처 회신 #2 로 자재가 두 갈래 — DSRE 병행분은 그쪽 MAT_CD, 단독분은 우리 채번).
--     그래서 **우리는 100001 부터** 쓴다. DSRE 연간 증가량 실측이 평균 약 1,500건
--     (최고 2,943건/2023년)이라 10만에 닿기까지 30~58년 — 실질 충돌 없음.
--   · 덤으로 "10만 이상이면 우리 자재"라는 판별 규칙이 한 줄로 서고,
--     장래 DSRE 자재를 우리 테이블로 합칠 일이 생기면 1~99999 대역이 비어 있어 그대로 들어온다.
--
-- 컬럼 변경은 없다(materials.code VARCHAR(30) 그대로). 이 행이 없으면
-- SequenceService.next() 가 "채번 시퀀스 없음" 으로 터져 **자재 등록이 전부 500** 이다.
