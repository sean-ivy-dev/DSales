-- 거래순번을 **주문(매출등록) 단위**로 (10/27 명세 §3-6·§8-2, 10/30 프론트 B-2).
--
-- 명세 §3-6: "거래처별로 매일 1번부터 매긴다. 예: 한 거래처가 **하루에 5번 주문하면 1~5**."
-- 명세 §8-2: "출고 등록을 하면 **주문 단위**로 작업요청서에 보이게 한다.
--             출고 등록 화면에도 거래순번(**첫 번째 주문 1, 두 번째 주문 2**)이 있다."
--
-- ‼️기존 구현은 순번을 **발송(작업요청서) 단위**에 얹었다. 발송은
--   (거래일자 + 거래처 + 학교 + 거래분류)로 묶이고 순번은 그 발송이 **새로 생길 때 한 번만**
--   매겨진다. 그래서 같은 날 같은 학교로 5번 주문하면 발송 1건에 합쳐져 **순번도 1개**가 됐다
--   (프론트 지적 그대로). §3-6 예시와 §8-2 둘 다 어긴다.
--
-- ★"주문 1건"의 식별자는 이미 있다 — **등록번호(entry_no, `E-20261027-55`)**.
--   매출등록 한 번에 하나씩 생기므로 "등록 1회 = 주문 1건"이 그대로 성립한다.
--   발송 묶음 키에 이 값을 더하면 **등록이 다르면 작업요청서도 갈린다**(§8-2).
--
-- 위탁출고는 여기서 건드리지 않는다 — 위탁은 출고번호(OUT-)가 **품목마다** 생겨
-- 주문 식별자로 쓸 수 없다. entry_no 를 NULL 로 두면 기존 묶음 동작 그대로다.

ALTER TABLE shipment
    ADD COLUMN entry_no VARCHAR(30) NULL
        COMMENT '주문 식별자 = 매출등록번호(E-). 등록 1회 = 주문 1건. 위탁출고는 NULL';

-- 발송 묶음 키 조회(tradeDate+partner+school+tradeClass+entryNo)에 쓴다.
CREATE INDEX ix_shipment_entry ON shipment (trade_date, partner_id, entry_no);

ALTER TABLE sales
    ADD COLUMN trade_seq INT NULL
        COMMENT '거래순번 — 그 거래처의 그 날 몇 번째 주문인가(등록 단위, 1부터)';

-- 조회 조건 "거래처 + 거래일자 + 거래순번"(프론트 B-2③)이 이 순서로 탄다.
CREATE INDEX ix_sales_trade_seq ON sales (partner_id, sales_date, trade_seq);
