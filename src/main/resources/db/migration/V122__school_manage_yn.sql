-- 학교 **관리대상 여부**(레거시 `schAllData.manageYN`). 근거: 응시현황 F-22.
--
-- ‼️레거시 응시현황 쿼리가 이 칸으로 학교를 거른다 (`응시현황.vb` AllSch 서브쿼리):
--     WHERE manageYN IS NULL OR manageYN = 'Y'
--   이 칸을 이관하지 않아 **관리대상이 아닌 학교 433곳(인원 21.9만 명)이 집계에 섞였다**.
--   그래서 라이브 지역비율이 레거시보다 20% 컸다(인원 129.2만 ↔ 레거시 108.0만).
--
-- ★목표값: `manageYN='Y'` 만 세면 **학교 1,847곳 · 인원 1,080,253명** (레거시 실측).
--
-- ★기본값을 'Y' 로 둔다 — 이관 대상이 아닌 학교(DSRE 동기화분·수기 등록분)는
--   레거시가 판단한 적이 없으므로 <b>빼지 않는다</b>. 빼면 그 학교 재고·매출이 통째로 사라진다.
--   거르는 쪽(제외)을 기본으로 하면 "안 보이는데 왜인지 모르는" 학교가 생긴다.

ALTER TABLE schools
    ADD COLUMN manage_yn VARCHAR(1) NOT NULL DEFAULT 'Y'
        COMMENT '관리대상 여부(레거시 schAllData.manageYN). N = 응시현황 집계에서 제외';
