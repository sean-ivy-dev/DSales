-- 매입입고 **매입률**(F-13). 발주처 검수 2026-11-05 —
--   "입고구분 「매입입고」 선택 시 **매입률 입력칸 추가** (발주처가 원기획 때 누락했다고 명시)".
--
-- ★레거시에 선례가 있다(2026-11-09 확인). 대성교재 `salesData` 입고행 **33,221건**에
--   `supRate` 가 찍혀 있다 — 85% 10,640 · 75% 10,279 · 50% 3,432 · 60% 3,410 · 80% 2,077 …
--   계산식도 같은 행에서 검산된다: **매입액 = 정가 × 매입률/100 × 수량**(100% 일치).
--
-- ★★**입고 건별**이다. 도서 마스터(`bookData`)에는 매입률 칸이 **없고**,
--   같은 도서가 **같은 해에도 매입률 3종**을 갖는 경우가 있다(H2016F-06·H2018R-01).
--   그래서 도서 기본값을 두지 않는다 — 두면 "왜 내가 넣은 값과 다르지"가 생긴다.
--
-- ‼️`inventory_txn` 에 둔다. 입고 한 줄이 곧 한 건의 매입이고, 그 시점 값이 남아야
--   나중에 단가를 고쳐도 과거 매입액이 움직이지 않는다(`unitCost` 와 같은 자리).
ALTER TABLE inventory_txn
    ADD COLUMN purchase_rate INT NULL
        COMMENT '매입률 %(매입입고 전용). 매입단가 = 정가 × 매입률/100. 레거시 salesData.supRate';
