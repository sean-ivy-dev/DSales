-- 「매출만(배송X)」 체크 상태 보존 — 프론트 B-4④.
--
-- 요청: "GET /sales 응답에 「매출만(배송X)」 여부(onlySales)를 실어 주세요 —
--        **불러온 주문을 고칠 때 체크 상태를 그대로 보여야** 합니다."
--
-- ‼️지금까지 `onlySales` 는 **등록 요청에서만 쓰이고 버려졌다**. 작업요청서를 만들지
--   말지 판단하는 데만 쓰고 저장하지 않았다. 그래서 주문을 불러와 고칠 때 담당자가
--   체크했었는지 알 길이 없다 — 다시 등록하면 체크가 풀린 채로 저장된다.
--
-- ★**파생으로 대신할 수 없다.** "발송이 없는 매출"로 유추하면 특강·창고없음 건까지
--   매출만으로 보인다(그 둘도 작업요청서를 만들지 않는다). 담당자가 실제로 체크한
--   사실과 "결과적으로 발송이 없다"는 서로 다른 말이다.
--
-- 이관분·이 컬럼 도입 전 매출은 NULL 이다. 소급해 채우면 없던 의도를 만드는 것이다.
-- (조회·수정에서는 NULL 을 '체크 안 함'으로 본다 — 발송이 있는지는 작업요청서가 답한다.)
ALTER TABLE sales
    ADD COLUMN only_sales TINYINT(1) NULL
        COMMENT '매출만(배송X) 체크 여부. 등록 시 담당자가 고른 값 — 작업요청서를 만들지 않는다';
