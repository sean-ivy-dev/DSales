-- 배송지(우편번호·주소). 근거: 특약점팀 전달 2026-11-03 요청 2번 —
-- "신청 화면은 학교 주소를 미리 채우고 「배송지 정보가 다를 경우 직접 수정」하게 되어 있다.
--  지금은 받는 칸이 없어 저장되지 않는다. 주문별로 저장해 작업요청서에서 그 배송지로 나가게."
--
-- ★왜 shipment 인가 — 배송지는 **그 발송 건**의 정보다(수령인명·연락처·이메일과 같은 축,
--   V44·V111). 거래처 마스터 주소와 다를 수 있고(그게 이 요청의 핵심이다) 주문마다 다르다.
--   ‼️거래처 마스터 주소를 고치는 것이 아니다 — 10/26 §4 "거래처관리 원본은 UPDATE하지 않는다"와
--     같은 원칙이다.
--
-- 길이는 DSRE 주문 등록(OrderCreateRequest.zipCode @Size(max=7))과 맞춘다.

ALTER TABLE shipment
    ADD COLUMN zip_code VARCHAR(7)   NULL COMMENT '배송지 우편번호(주문별). 특약점 신청 화면 입력',
    ADD COLUMN address  VARCHAR(300) NULL COMMENT '배송지 주소(주문별). 학교 주소 기본값을 사용자가 고칠 수 있다';
